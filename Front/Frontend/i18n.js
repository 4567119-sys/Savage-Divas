let currentLang = 'en';

function t(key) {
  if (I18N_DATA[currentLang] && I18N_DATA[currentLang][key]) {
    return I18N_DATA[currentLang][key];
  }
  if (I18N_DATA['en'][key]) {
    return I18N_DATA['en'][key];
  }
  return key;
}

function setLanguage(lang) {
  if (I18N_DATA[lang]) {
    currentLang = lang;
    localStorage.setItem('rsf_lang', lang);
    applyTranslations();
    document.dispatchEvent(new CustomEvent('rsf:languagechanged', { detail: { lang: currentLang } }));
  }
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = t(key);
    if (text) {
      el.textContent = text;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const text = t(key);
    if (text) {
      el.setAttribute('placeholder', text);
    }
  });

  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    const text = t(key);
    if (text) {
      el.setAttribute('aria-label', text);
    }
  });

  document.documentElement.lang = currentLang;

  const announcer = document.getElementById('sr-announcer');
  if (announcer) {
    announcer.textContent = `Language switched to ${I18N_DATA[currentLang].langName}`;
  }
}


